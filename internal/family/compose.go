package family

import (
	"fmt"
	"strings"
)

// Paths lock up uses on the host.
type Paths struct {
	// HubData is the hub's data directory (outside the projects
	// directory: no agent container mounts it).
	HubData string
	// FacadeDir holds the facade socket ($XDG_RUNTIME_DIR/lockhub).
	FacadeDir string
	// HubPub is the hub's public key file, mounted read-only in locks.
	HubPub string
	// User is the uid:gid the hub runs as, so that the host user owns
	// the facade socket and the data ("0:0" under rootless engines, where
	// root is the host user).
	User string
	// Devices is the pinned devices file (host state dir), mounted
	// read-only in every lock; "" when no device is paired. DevicesID
	// names its content: as a label of every lock, a change of the
	// paired devices recreates the locks, which read the file at start.
	Devices   string
	DevicesID string
	// Config is the fingerprint of the applied configuration (keys,
	// routing). As a label of the hub service, a change of it makes
	// compose recreate the hub, which reads its config at start.
	Config string
}

func q(s string) string { return fmt.Sprintf("%q", s) }

// Compose renders the compose file. Output is deterministic.
func Compose(c *Config, p Paths) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("# Generated by lock up from lockfamily.yaml. Do not edit: run lock up.")
	w("services:")
	w("  lockhub:")
	w("    image: %s", q(c.Hub.Image))
	w("    user: %s", q(p.User))
	if m := c.Hub.Mobile; m != nil {
		w("    command: [\"serve\", \"--listen\", \":8443\", \"--data\", \"/var/lib/lockhub\", \"--facade-socket\", \"/run/lockhub-facade/facade.sock\", \"--mobile-listen\", \":8444\", \"--mobile-origin\", %s]", q(m.Origin))
		// Published on the host's loopback only: the human's reverse
		// proxy or tunnel forwards the origin to it.
		w("    ports: [%s]", q(fmt.Sprintf("127.0.0.1:%d:8444", m.Port)))
	} else {
		w("    command: [\"serve\", \"--listen\", \":8443\", \"--data\", \"/var/lib/lockhub\", \"--facade-socket\", \"/run/lockhub-facade/facade.sock\"]")
	}
	hardening(w)
	w("    volumes:")
	w("      - type: bind")
	w("        source: %s", q(p.HubData))
	w("        target: /var/lib/lockhub")
	w("      - type: bind")
	w("        source: %s", q(p.FacadeDir))
	w("        target: /run/lockhub-facade")
	// The hub has no route out, unless a chat facade must reach its
	// service: then through its own network, never a lock's.
	// Its own networks: a chat facade's route out, the mobile listener's
	// published port (an internal network publishes none).
	nets := []string{"lockhub"}
	if c.ChatEnabled() {
		nets = append(nets, q("egress-hub"))
	}
	if c.Hub.Mobile != nil {
		nets = append(nets, q("mobile-hub"))
	}
	w("    networks: [%s]", strings.Join(nets, ", "))
	if p.Config != "" {
		w("    labels:")
		w("      lockfamily.config: %s", q(p.Config))
	}
	w("    restart: unless-stopped")
	for _, name := range c.Instances() {
		l := c.Locks[name]
		w("  lock-%s:", name)
		w("    image: %s", q(l.Image))
		w("    command: [\"console\", \"--hub\", \"http://lockhub:8443\", \"--hub-plain-http\", \"--hub-key-file\", \"/run/lockfamily/hub.pub\", \"--instance\", %s%s]", q(name), deviceFlags(c, l, p))
		hardening(w)
		w("    volumes:")
		w("      - %s:/run/%s", q(name+"-run"), l.Type)
		w("      - %s:/home/%s", q(name+"-home"), l.Type)
		w("      - type: bind")
		w("        source: %s", q(p.HubPub))
		w("        target: /run/lockfamily/hub.pub")
		w("        read_only: true")
		if p.Devices != "" && l.Devices {
			w("      - type: bind")
			w("        source: %s", q(p.Devices))
			w("        target: /run/lockfamily/devices.json")
			w("        read_only: true")
		}
		w("    networks: [lockhub, %s]", q("egress-"+name))
		w("    depends_on: [lockhub]")
		if p.DevicesID != "" && l.Devices {
			w("    labels:")
			w("      lockfamily.devices: %s", q(p.DevicesID))
		}
		w("    restart: unless-stopped")
	}
	w("networks:")
	w("  lockhub:")
	w("    internal: true")
	if c.ChatEnabled() {
		w("  %s: {}", q("egress-hub"))
	}
	if c.Hub.Mobile != nil {
		w("  %s: {}", q("mobile-hub"))
	}
	for _, name := range c.Instances() {
		w("  %s: {}", q("egress-"+name))
	}
	w("volumes:")
	for _, name := range c.Instances() {
		w("  %s: {}", q(name+"-run"))
		w("  %s: {}", q(name+"-home"))
	}
	return b.String()
}

// deviceFlags are a lock's flags for the paired devices: pinned, and as
// hub.mobile asks, sealed to and required; only for a lock that takes
// them (locks.<name>.devices).
func deviceFlags(c *Config, l Lock, p Paths) string {
	if p.Devices == "" || !l.Devices {
		return ""
	}
	out := `, "--devices-file", "/run/lockfamily/devices.json"`
	if m := c.Hub.Mobile; m != nil {
		if m.SealClear {
			out += `, "--seal-clear"`
		}
		if len(m.RequireDevice) > 0 {
			out += `, "--require-device", ` + q(strings.Join(m.RequireDevice, ","))
		}
	}
	return out
}

func hardening(w func(string, ...any)) {
	w("    read_only: true")
	w("    cap_drop: [ALL]")
	w("    security_opt: [\"no-new-privileges:true\"]")
	w("    tmpfs: [\"/tmp:size=16m\"]")
	w("    pids_limit: 256")
	w("    mem_limit: 512m")
}
